  var cy = (box.y1 + underlineY1) / 2;
  var maxWidth = (box.x2 - box.x1) * 0.96;
  var maxHeight = underlineY1 - box.y1;
  var fontSize = Math.floor(maxHeight * 0.62);
  var width;

